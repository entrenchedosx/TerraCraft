/* Copy one glyph's rows (blank for out-of-range codes). */
void font_glyph(char c, uint8_t out_rows[8])
{
    if (out_rows == NULL) {
        return;
    }
    unsigned char uc = (unsigned char)c;
    if (uc < FONT_FIRST || uc >= FONT_FIRST + FONT_COUNT) {
        memset(out_rows, 0, 8);
        return;
    }
    memcpy(out_rows, FONT[uc - FONT_FIRST], 8);
}

/* Advance helper: cell width in scaled pixels. */
static float cell_w(float scale)
{
    return (float)FONT_W * scale;
}

/* Measure text extents. */
void font_measure(const char *text, float scale, float *out_w, float *out_h)
{
    float w = 0.0f;
    float h = 0.0f;
    if (text != NULL && scale > 0.0f) {
        float line = 0.0f;
        float maxw = 0.0f;
        int lines = 1;
        for (const char *p = text; *p != '\0'; ++p) {
            if (*p == '\n') {
                if (line > maxw) {
                    maxw = line;
                }
                line = 0.0f;
                ++lines;
            } else if (*p == '\t') {
                line += cell_w(scale) * 4.0f;
            } else {
                line += cell_w(scale);
            }
        }
        if (line > maxw) {
            maxw = line;
        }
        w = maxw;
        h = (float)lines * (float)FONT_H * scale;
    }
    if (out_w != NULL) {
        *out_w = w;
    }
    if (out_h != NULL) {
        *out_h = h;
    }
}

/* Append one pixel quad (two triangles, 6 verts of 6 floats). */
static size_t emit_px(float *dst, size_t cap, size_t n, float x, float y, float s, float r, float g, float b,
                      float a)
{
    if (dst == NULL || n + 6 > cap) {
        return n;
    }
    float x1 = x + s;
    float y1 = y + s;
    float *v = dst + n * 6;
    v[0] = x;
    v[1] = y;
    v[2] = r;
    v[3] = g;
    v[4] = b;
    v[5] = a;
    v[6] = x1;
    v[7] = y;
    v[8] = r;
    v[9] = g;
    v[10] = b;
    v[11] = a;
    v[12] = x;
    v[13] = y1;
    v[14] = r;
    v[15] = g;
    v[16] = b;
    v[17] = a;
    v[18] = x;
    v[19] = y1;
    v[20] = r;
    v[21] = g;
    v[22] = b;
    v[23] = a;
    v[24] = x1;
    v[25] = y;
    v[26] = r;
    v[27] = g;
    v[28] = b;
    v[29] = a;
    v[30] = x1;
    v[31] = y1;
    v[32] = r;
    v[33] = g;
    v[34] = b;
    v[35] = a;
    return n + 6;
}

/* Rasterize text into colored quads. */
size_t font_build_quads(const char *text, float x, float y, float scale, float r, float g, float b, float a,
                        float *out_verts, size_t cap_verts)
{
    if (text == NULL || out_verts == NULL || cap_verts == 0 || !(scale > 0.0f)) {
        return 0;
    }
    size_t n = 0;
    float cx = x;
    float cy = y;
    uint8_t rows[8];
    for (const char *p = text; *p != '\0'; ++p) {
        char c = *p;
        if (c == '\n') {
            cx = x;
            cy += (float)FONT_H * scale;
            continue;
        }
        if (c == '\t') {
            cx += cell_w(scale) * 4.0f;
            continue;
        }
        font_glyph(c, rows);
        for (int row = 0; row < FONT_H; ++row) {
            uint8_t bits = rows[row];
            for (int col = 0; col < FONT_W; ++col) {
                if (bits & (0x80u >> col)) {
                    n = emit_px(out_verts, cap_verts, n, cx + (float)col * scale, cy + (float)row * scale,
                                scale, r, g, b, a);
                    if (n + 6 > cap_verts) {
                        return n; /* Full: stop mid-glyph rather than overflow. */
                    }
                }
            }
        }
        cx += cell_w(scale);
    }
    return n;
}
